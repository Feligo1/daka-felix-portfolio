-- Portfolio v3: reusable form presets for admin publishing.
-- Additive migration. Applied to Supabase project pthcviwhcsluovdekjub on 22 November 2026.
-- Options are admin-only and don't alter historical certificate, journal or gallery entries.
create table if not exists public.portfolio_form_options (
 id bigint generated by default as identity primary key,
 section text not null check (section in ('gallery','journal','certificate','project')),
 field_name text not null check (field_name in ('title','category','topic','issuer','type')),
 label text not null check (length(trim(label)) between 1 and 160),
 sort_order integer not null default 0,
 is_active boolean not null default true,
 created_at timestamptz not null default now(),
 unique (section,field_name,label)
);
alter table public.portfolio_form_options enable row level security;
drop policy if exists "Authorized admins read form options" on public.portfolio_form_options;
create policy "Authorized admins read form options" on public.portfolio_form_options
 for select to authenticated using (public.is_portfolio_admin());
drop policy if exists "Authorized admins manage form options" on public.portfolio_form_options;
create policy "Authorized admins manage form options" on public.portfolio_form_options
 for all to authenticated using (public.is_portfolio_admin()) with check (public.is_portfolio_admin());
grant select,insert,update,delete on public.portfolio_form_options to authenticated;
grant usage,select on sequence public.portfolio_form_options_id_seq to authenticated;

